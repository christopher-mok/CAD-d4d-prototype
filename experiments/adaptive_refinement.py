"""Baseline adaptive-refinement experiment.

    python experiments/adaptive_refinement.py [--config configs/adaptive_refinement.yaml] [--quick]

Target: a cube-sphere with a global anisotropic deformation (representable by
the coarse model) plus a localized bump generated by LocalRefine + displacement
(not representable by the coarse model). The generating program is discarded;
only the frozen target geometry (SDF + coverage samples) is used.

Compared (identical continuous budget):
  1. fixed coarse                     (6 Bezier faces)
  2. fixed uniform (k knots)          uniformly refined faces and carriers
  3. adaptive SRD, naive scoring      (mode A)
  4. adaptive SRD, marginal, no birth (mode B, ablation)
  5. adaptive SRD, marginal + birth   (mode C, the method)
  6. adaptive SRD, mode C, uniform proposal sampling (ablation)
"""
from __future__ import annotations

import argparse
import csv
import dataclasses
import json
import sys
import time
from pathlib import Path

import numpy as np
import torch
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from cad_d4d.device import get_device, to_numpy, to_tensor  # noqa: E402
from cad_d4d.geometry.builders import build_cube_complex  # noqa: E402
from cad_d4d.geometry.state import watertightness_error  # noqa: E402
from cad_d4d.geometry.tessellation import SamplingConfig, SurfaceSampler  # noqa: E402
from cad_d4d.losses.complexity import ComplexityConfig, structural_complexity  # noqa: E402
from cad_d4d.losses.coverage import coverage_distances  # noqa: E402
from cad_d4d.losses.objective import ObjectiveConfig, ShapeObjective  # noqa: E402
from cad_d4d.optimization.continuous import ContinuousConfig, ContinuousOptimizer  # noqa: E402
from cad_d4d.optimization.proposal_sampling import ProposalConfig  # noqa: E402
from cad_d4d.optimization.rewrite_scoring import ScoringConfig  # noqa: E402
from cad_d4d.optimization.srd import SRD, SRDConfig  # noqa: E402
from cad_d4d.targets.synthetic import TargetConfig, localized_bump_target, scale_dofs  # noqa: E402
from cad_d4d.visualization.viewer import plot_comparison, plot_history, save_state_figure, view_toward  # noqa: E402


def load_config(path: Path, quick: bool) -> dict:
    cfg = yaml.safe_load(path.read_text())
    if quick:
        cfg["budget"] = {"rounds": 6, "steps_per_round": 30}
        cfg["target"]["sdf_res"] = 48
        cfg["target"]["n_coverage"] = 1500
        cfg["uniform_knots"] = [3]
        cfg["srd_seeds"] = [cfg["seed"]]
    return cfg


def independent_metrics(state, target) -> dict:
    """Fit measured on a dense, method-independent sampling (not the optimizer's quadrature)."""
    sm = SurfaceSampler(state, SamplingConfig(min_res=33, per_span=8, max_res=65))
    X, Xu, Xv = sm.evaluate_np(state.values())
    area = np.linalg.norm(np.cross(Xu, Xv), axis=1) * to_numpy(sm.quad_w)
    w = area / area.sum()
    phi = to_numpy(target.sdf(X, exact=True))  # exact narrow-band distance for reporting
    d, _ = coverage_distances(target.points, to_tensor(X), sm.tri_t)
    d = to_numpy(d)
    return {"sdf_rms": float(np.sqrt(np.sum(w * phi**2))), "coverage_rms": float(np.sqrt(np.mean(d**2))),
            "coverage_max": float(d.max()), "fit_dense": float(np.sum(w * phi**2) + np.mean(d**2))}


def summarize(name, state, obj, runtime, events=(), extra=None) -> dict:
    rep = obj.report(state)
    cc = obj.cfg.complexity
    out = {
        "method": name, "fit": rep["fit"], "sdf": rep["sdf"], "coverage": rep["coverage"], "fair": rep["fair"],
        "n_faces": state.n_faces, "n_cp": state.n_control_points,
        "complexity": structural_complexity(state, cc),
        "total": rep["fit"] + obj.cfg.lambda_fair * rep["fair"] + cc.lambda_complex * structural_complexity(state, cc),
        "accepted_refinements": sum(1 for e in events if e["refinement"]),
        "accepted_simplifications": sum(1 for e in events if not e["refinement"]),
        "refinements_later_simplified": sum(1 for r in state.birth_records if r.simplified),
        "runtime_s": runtime, "watertight_err": watertightness_error(state),
    }
    out.update(independent_metrics(state, obj.target))
    out.update(extra or {})
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default=str(ROOT / "configs" / "adaptive_refinement.yaml"))
    ap.add_argument("--quick", action="store_true", help="short smoke run")
    args = ap.parse_args()
    cfg = load_config(Path(args.config), args.quick)
    out_dir = ROOT / cfg["output_dir"]
    out_dir.mkdir(parents=True, exist_ok=True)
    np.random.seed(cfg["seed"])
    torch.manual_seed(cfg["seed"])

    # ---- target (generated from the grammar, program discarded) ----------
    print(f"device: {get_device()}")
    t0 = time.perf_counter()
    base = build_cube_complex()
    tc = cfg["target"]
    target = localized_bump_target(
        base, face_index=tc["face_index"], uv=tuple(tc["uv"]), width=tc["width"], height=tc["height"],
        refine_knots=tc["refine_knots"], extra=scale_dofs(tuple(tc["global_scale"])),
        cfg=TargetConfig(sdf_res=tc["sdf_res"], n_coverage=tc["n_coverage"], seed=cfg["seed"]))
    gt = target.ground_truth
    print(f"target built in {time.perf_counter() - t0:.1f}s: ground truth has {gt.n_faces} faces, "
          f"{gt.n_control_points} control points (not visible to the optimizer)")

    oc = cfg["objective"]
    cc = ComplexityConfig(**oc["complexity"])
    obj_cfg = ObjectiveConfig(lambda_sdf=oc["lambda_sdf"], lambda_coverage=oc["lambda_coverage"],
                              lambda_normal=oc["lambda_normal"], lambda_fair=oc["lambda_fair"], complexity=cc)
    obj = ShapeObjective(target, obj_cfg)
    cont = ContinuousConfig(eta=cfg["continuous"]["eta"])
    R, K = cfg["budget"]["rounds"], cfg["budget"]["steps_per_round"]
    n_steps = R * K

    results, histories, finals, srd_runs = {}, {}, {}, {}

    def fixed(name, state):
        t = time.perf_counter()
        hist = []
        opt = ContinuousOptimizer(obj, cont)
        logs = opt.run(state, n_steps)
        for i, lg in enumerate(logs):
            hist.append({"step": i + 1, "loss": lg["loss"], "sdf": lg["sdf"], "coverage": lg["coverage"],
                         "fair": lg["fair"], "n_cp": state.n_control_points,
                         "total": lg["loss"] + cc.lambda_complex * structural_complexity(state, cc)})
        rt = time.perf_counter() - t
        results[name] = summarize(name, state, obj, rt)
        histories[name] = hist
        finals[name] = state
        print(f"[{name}] fit={results[name]['fit']:.3e} cp={state.n_control_points} ({rt:.1f}s)")

    fixed("fixed coarse", base.copy())
    for k in cfg["uniform_knots"]:
        fixed(f"fixed uniform k={k}", build_cube_complex(n_interior_knots=k))

    pc = cfg["proposals"]
    variants = [("adaptive naive (A)", "naive", "residual"),
                ("adaptive marginal, no birth (B)", "marginal", "residual"),
                ("adaptive marginal + birth (C)", "marginal_birth", "residual"),
                ("adaptive C, uniform proposals", "marginal_birth", "uniform")]
    seeds = cfg.get("srd_seeds", [cfg["seed"]])
    per_seed: dict[str, list] = {}
    for name, mode, pmode in variants:
        runs = []
        for seed in seeds:
            sc = SRDConfig(rounds=R, steps_per_round=K, seed=seed, continuous=cont,
                           scoring=ScoringConfig(mode=mode),
                           proposals=ProposalConfig(mode=pmode, n_refine=pc["n_refine"], n_simplify=pc["n_simplify"],
                                                    eps_remove=pc["eps_remove"], eps_merge=pc["eps_merge"]),
                           **cfg["srd"])
            res = SRD(obj, sc).run(base)
            summ = summarize(name, res.state, obj, res.runtime, res.events, {"seed": seed})
            runs.append((summ, res))
            print(f"[{name} | seed {seed}] fit_dense={summ['fit_dense']:.3e} cp={res.state.n_control_points} "
                  f"refine={summ['accepted_refinements']} simplify={summ['accepted_simplifications']} "
                  f"({res.runtime:.1f}s)")
        per_seed[name] = [r[0] for r in runs]
        rep_summ, rep_run = sorted(runs, key=lambda r: r[0]["fit_dense"])[len(runs) // 2]  # median-fit run
        results[name] = rep_summ
        histories[name] = rep_run.history
        finals[name] = rep_run.state
        srd_runs[name] = rep_run

    # ---- outputs ------------------------------------------------------------
    (out_dir / "metrics.json").write_text(json.dumps({"representative": results, "per_seed": per_seed}, indent=2))
    lines = ["Fit = exact narrow-band SDF^2 + coverage^2 on a dense independent sampling. Adaptive rows: median over "
             f"SRD seeds {seeds} [min - max]; fixed rows are deterministic.", "",
             "| method | fit (median) | fit range | control pts | faces | complexity | total objective "
             "| refinements | simplifications | runtime / run (s) |", "|" + "---|" * 10]

    def med(rows, key):
        return float(np.median([r[key] for r in rows]))

    for name, r in results.items():
        rows = per_seed.get(name, [r])
        tot = [x["fit_dense"] + obj.cfg.lambda_fair * x["fair"] + cc.lambda_complex * x["complexity"] for x in rows]
        lines.append(f"| {name} | {med(rows, 'fit_dense'):.2e} | {min(x['fit_dense'] for x in rows):.2e} - "
                     f"{max(x['fit_dense'] for x in rows):.2e} | {med(rows, 'n_cp'):.0f} | {med(rows, 'n_faces'):.0f} | "
                     f"{med(rows, 'complexity'):.0f} | {float(np.median(tot)):.3e} | "
                     f"{med(rows, 'accepted_refinements'):.0f} | {med(rows, 'accepted_simplifications'):.0f} | "
                     f"{med(rows, 'runtime_s'):.1f} |")
    (out_dir / "metrics.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))

    main_name = "adaptive marginal + birth (C)"
    main = srd_runs[main_name]
    with open(out_dir / "exact_refinement_log.csv", "w", newline="") as fh:
        keys = ["round", "step", "kind", "face", "D_old", "D_new", "B_refine", "predicted_improvement",
                "birth_cost", "delta_complexity", "immediate_gain", "score", "status", "accepted"]
        wr = csv.DictWriter(fh, fieldnames=keys, extrasaction="ignore")
        wr.writeheader()
        for p in main.proposals:
            if p.get("refinement") and p.get("ok"):
                wr.writerow(p)
    with open(out_dir / "events_C.json", "w") as fh:
        json.dump({"events": main.events, "counterfactuals": main.counterfactuals,
                   "birth_records": [dataclasses.asdict(r) for r in main.state.birth_records],
                   "rounds": main.rounds}, fh, indent=2, default=str)
    with open(out_dir / "proposals_C.json", "w") as fh:
        json.dump(main.proposals, fh, indent=1, default=str)

    plot_history({k: histories[k] for k in ["fixed coarse", f"fixed uniform k={cfg['uniform_knots'][-1]}",
                                            "adaptive naive (A)", main_name]},
                 str(out_dir / "history.png"), events={main_name: main.events})
    plot_comparison({k: {"n_cp": v["n_cp"], "fit": v["fit_dense"]} for k, v in results.items()},
                    str(out_dir / "fit_vs_control_points.png"), highlight=main_name)
    feature_face = sorted(base.cx.faces)[tc["face_index"]]
    view = view_toward(base.evaluate(feature_face, np.array([tc["uv"]]))[0])
    for name, st in finals.items():
        props = srd_runs[name].proposals if name in srd_runs else None
        slug = name.replace(" ", "_").replace("(", "").replace(")", "").replace(",", "").replace("=", "")
        save_state_figure(st, target, str(out_dir / f"state_{slug}.png"), proposals=props, title=name, view=view)
    print(f"\nwrote outputs to {out_dir}")


if __name__ == "__main__":
    main()
